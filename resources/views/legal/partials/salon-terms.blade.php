    <h3>۷. شرایط ثبت‌نام و احراز</h3>
    <ul>
        <li>سالن باید پروانه‌ی کسب معتبر (درگاه ملی مجوزها) برای خدمت‌هایی که عرضه می‌کند داشته باشد. مالک، کد ملی، نوع پروانه، شناسه‌ی یکتای پروانه
            و تصویر آن را وارد می‌کند؛ تا تأیید پلتفرم، صفحه‌ی عمومی و رزرو سالن بسته می‌ماند (دستورالعمل ساماندهی سکوهای اینترنتی).</li>
        <li>اطلاعات سالن (نام، نشانی، تلفن، خدمات، قیمت‌ها، قوانین لغو) باید درست و به‌روز باشد؛ تبلیغ فریبنده و نظر ساختگی ممنوع است.</li>
    </ul>

    <h3>۸. اشتراک و پرداخت</h3>
    <ul>
        <li>هزینه‌ی اشتراک، دوره و امکانات هر پلن پیش از خرید در صفحه‌ی خرید نشان داده می‌شود و فاکتور آن در پنل سالن می‌ماند.</li>
        <li>پول مشتری‌ها با درگاه پرداخت خود سالن (مرچنت سالن) دریافت می‌شود.</li>
    </ul>

    <h3>۹. داده‌ی مشتری‌ها</h3>
    <p>
        سالن اطلاعات مشتری‌های خودش را فقط برای ارائه‌ی خدمت و ارتباط با همان مشتری به کار می‌برد، پیامک تبلیغاتی را فقط با امکان انصراف می‌فرستد
        (ماده‌ی ۵۵) و عکس قبل و بعد را فقط با رضایت صریح مشتری می‌گیرد (ماده‌ی ۵۸).
    </p>

    <h3>۱۰. تعلیق و پایان</h3>
    <p>
        پلتفرم سالنی را که اطلاعات نادرست بدهد، پروانه‌ی معتبر نداشته باشد یا خلاف این شرایط رفتار کند، پس از اطلاع تعلیق می‌کند. با پایان
        اشتراک، صفحه‌ی عمومی و رزرو بسته می‌شود و داده‌ها طبق حریم خصوصی نگه داشته یا پاک می‌شوند.
    </p>

    <h3>۱۱. قانون حاکم</h3>
    <p>این شرایط تابع قوانین جمهوری اسلامی ایران است. شرطی که خلاف قانون یا به زیان غیرمنصفانه‌ی مصرف‌کننده باشد اثری ندارد (ماده‌ی ۴۶).</p>
