    public static function get(string $key): array
    {
        return self::all()[$key] ?? throw new \InvalidArgumentException("Unknown SMS template [{$key}]");
    }

    /** نام جای‌خالی‌های یک متن: {تاریخ} → تاریخ */
    public static function placeholdersIn(string $body): array
    {
        preg_match_all('/\{([^{}\s]+)\}/u', $body, $m);

        return array_values(array_unique($m[1]));
    }

    /**
     * متن نهایی: جای‌خالی‌ها با مقدار (Closure فقط اگر در متن هست اجرا می‌شود — مثلاً لینک کوتاه که ردیف می‌سازد)، فاصله‌های تکراری
     * که از جای‌خالی خالی می‌مانند یکی و دو سر متن trim می‌شود.
     *
     * @param  array<string, string|int|float|\Closure|null>  $vars
     */
    public static function fill(string $body, array $vars): string
    {
        $text = preg_replace_callback('/\{([^{}\s]+)\}/u', function ($m) use ($vars) {
            if (! array_key_exists($m[1], $vars)) {
                return '';
            }
            $value = $vars[$m[1]];

            return (string) ($value instanceof \Closure ? $value() : $value);
        }, $body);

        return trim(preg_replace('/ {2,}/u', ' ', (string) $text));
    }

    /** نمونه‌ی پیش‌نمایش با مقادیر نمونه‌ی هر جای‌خالی */
    public static function sample(string $key, ?string $body = null): string
    {
        $t = self::get($key);

        return self::fill($body ?? $t['default'], array_map(fn ($p) => $p[1], $t['placeholders']));
    }
