<?php

namespace App\Support;

/**
 * عنوان نمایشی سالن در متن‌های عمومی سایت (بسته‌ی «ح»، ۱۰، ۲۰۲۶-۱۰-۱۹).
 *
 * پیش‌تر «سالن زیبایی {نام}» ثابت بود؛ وقتی نام خودش «سالن زیبایی راستا» است، «درباره ما» و پانویس «سالن زیبایی سالن زیبایی
 * راستا» می‌شد. نامی که خودش نوع کسب‌وکار را می‌گوید دست نمی‌خورد.
 */
final class SalonTitle
{
    /** نام‌هایی با این آغاز پیشوند نمی‌گیرند */
    private const OWN_PREFIXES = ['سالن', 'آرایشگاه', 'کلینیک', 'استودیو', 'آتلیه', 'مرکز', 'خانه'];

    public static function for(string $name): string
    {
        $name = trim($name);
        $normalized = str_replace(["\u{200C}", 'ي', 'ك'], [' ', 'ی', 'ک'], $name);

        foreach (self::OWN_PREFIXES as $prefix) {
            if (str_starts_with($normalized, $prefix)) {
                return $name;
            }
        }

        return "سالن زیبایی {$name}";
    }

    /**
     * نام کوتاه برای زیر آیکون صفحه‌ی اصلی گوشی (PWA، ۲۰۲۶-۱۰-۲۱): پیشوند نوع کسب‌وکار («سالن زیبایی»، «آرایشگاه»…) برداشته می‌شود؛ آیفون
     * فقط حدود ۱۲ حرف نشان می‌دهد و «سالن زیبایی راستا» «سالن زیبایی…» می‌شد. اگر چیزی نماند (نام فقط «سالن زیبایی» است)، خود نام.
     */
    public static function short(string $name): string
    {
        $name = trim($name);
        $kind = ['سالن', 'زیبایی', 'آرایشگاه', 'آرایش', 'کلینیک', 'استودیو', 'آتلیه', 'مرکز', 'خانه', 'زنانه', 'بانوان', 'و', 'پوست', 'مو'];
        $short = $name;

        // اولین کلمه (تا فاصله یا نیم‌فاصله) اگر نوع کسب‌وکار است برداشته می‌شود؛ بقیه‌ی نام دست‌نخورده (نیم‌فاصله‌ی «ماه‌بانو» می‌ماند)
        while (preg_match('/^(\S+?)[\s\x{200C}]+(\S.*)$/u', $short, $m) && in_array(str_replace(['ي', 'ك'], ['ی', 'ک'], $m[1]), $kind, true)) {
            $short = $m[2];
        }

        // چیزی جز نوع کسب‌وکار نماند (نام فقط «سالن زیبایی» است) ← خود نام
        $rest = preg_split('/[\s\x{200C}]+/u', str_replace(['ي', 'ك'], ['ی', 'ک'], $short)) ?: [];

        return array_diff($rest, $kind) === [] ? $name : $short;
    }
}
